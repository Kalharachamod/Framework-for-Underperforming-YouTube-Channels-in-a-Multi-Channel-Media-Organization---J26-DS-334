"""Run the offline Component 2 demand-feasibility experiment."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import pandas as pd

from .audit import build_pilot_frame, build_sample_frame, dataset_audit, prediction_summary, write_json
from .baseline import detect_frame
from .config import ExperimentConfig
from .sampling import make_blinded_review_sample, write_review_outputs


def _summary_table(summary: dict[str, Any]) -> str:
    rows = ["| Channel | Comments | Candidate rows | Candidate rate |", "| --- | ---: | ---: | ---: |"]
    for row in summary["by_channel"]:
        rate = row["candidates"] / row["comments"] if row["comments"] else 0
        rows.append(f"| {row['channel_name']} | {row['comments']} | {row['candidates']} | {rate:.1%} |")
    return "\n".join(rows)


def _category_table(summary: dict[str, Any]) -> str:
    rows = ["| Channel | Experimental signal | Count |", "| --- | --- | ---: |"]
    for row in summary["by_category_and_channel"]:
        rows.append(f"| {row['channel_name']} | {row['primary_signal']} | {row['count']} |")
    return "\n".join(rows)


def _render_report(
    pilot_audit: dict[str, Any],
    sample_audit: dict[str, Any],
    pilot_summary: dict[str, Any],
    sample_summary: dict[str, Any],
    review: pd.DataFrame,
    config: ExperimentConfig,
) -> str:
    return f"""# Component 2 Audience-Demand Feasibility Experiment

This report was generated by the offline, deterministic experiment runner.
It contains aggregate counts only. Heuristic outputs are **unverified
candidates**, not ground-truth labels or estimates of true demand prevalence.

## Run configuration

- Experiment seed: `{config.seed}`
- Review rows requested: `{config.review_size}`
- Review rows generated: `{len(review)}`
- Candidate and control quotas: `{config.candidate_per_channel}` and `{config.control_per_channel}` per channel
- Existing 300-comment annotation sample was read only; it was not replaced or relabelled.
- Input hashes are recorded in `data_audit.json` under the ignored experiment output directory.

## Dataset coverage

- Pilot comments: `{pilot_audit['rows']}` rows, `{pilot_audit['unique_comment_ids']}` unique comments, `{pilot_audit['unique_videos']}` videos, `{pilot_audit['unique_channels']}` channels.
- Existing annotation sample: `{sample_audit['rows']}` rows, `{sample_audit['unique_comment_ids']}` unique comments, `{sample_audit['unique_videos']}` videos, `{sample_audit['unique_channels']}` channels.
- The pilot and sample retain video/channel context and the existing original/cleaned text fields.

## Baseline candidate summary

### Pilot

- Candidate rows: `{pilot_summary['candidate_count']}` (`{pilot_summary['candidate_rate']:.1%}` of pilot rows).

{_summary_table(pilot_summary)}

{_category_table(pilot_summary)}

### Existing 300-comment sample

- Candidate rows: `{sample_summary['candidate_count']}` (`{sample_summary['candidate_rate']:.1%}` of sample rows).

{_summary_table(sample_summary)}

{_category_table(sample_summary)}

## Interpretation limits

The rules are deliberately high-recall and expected to produce false
positives. They use comment text, cleaned text, and available video context,
but they do not prove that a request is unmet demand. Questions, topical
interest, praise, criticism, short reactions, emojis, and links require human
review. No classifier accuracy, precision, recall, or demand prevalence is
claimed by this run.

The blinded review file contains blank human fields and is intended to measure
candidate precision and false positives. A representative sample is required
before making prevalence or recall claims. A separate demand-enriched sample
may support model training and topic discovery after verification, but it must
remain separately identified from representative evaluation data.

## Optional methods

An optional local semantic adapter and an optional, disabled-by-default Gemini
structured-review adapter are included for later approval. Neither was run by
this experiment, neither changes production labels, and neither may write to
Supabase. Their model coverage, costs, and outputs require a separate review.
"""


def run(config: ExperimentConfig) -> dict[str, Any]:
    pilot = build_pilot_frame(config.pilot_comments, config.pilot_videos, config.preprocessed_comments)
    sample = build_sample_frame(config.annotation_sample)
    pilot_predictions = detect_frame(pilot)
    sample_predictions = detect_frame(sample)
    pilot_with_predictions = pd.concat([pilot.reset_index(drop=True), pilot_predictions.reset_index(drop=True)], axis=1)
    sample_with_predictions = pd.concat([sample.reset_index(drop=True), sample_predictions.reset_index(drop=True)], axis=1)
    pilot_with_predictions = pilot_with_predictions.loc[:, ~pilot_with_predictions.columns.duplicated()]
    sample_with_predictions = sample_with_predictions.loc[:, ~sample_with_predictions.columns.duplicated()]

    review, manifest = make_blinded_review_sample(
        pilot,
        pilot_predictions,
        seed=config.seed,
        candidate_per_channel=config.candidate_per_channel,
        control_per_channel=config.control_per_channel,
    )
    config.output_dir.mkdir(parents=True, exist_ok=True)
    pilot_with_predictions.to_csv(config.output_dir / "pilot_baseline_predictions.csv", index=False, encoding="utf-8")
    sample_with_predictions.to_csv(config.output_dir / "annotation_sample_baseline_predictions.csv", index=False, encoding="utf-8")
    write_review_outputs(review, manifest, config.output_dir)

    pilot_audit = dataset_audit(pilot_with_predictions, "pilot_comments", config.pilot_comments)
    sample_audit = dataset_audit(sample_with_predictions, "annotation_sample", config.annotation_sample)
    pilot_summary = prediction_summary(pilot_with_predictions)
    sample_summary = prediction_summary(sample_with_predictions)
    write_json(
        {
            "experiment_seed": config.seed,
            "pilot": pilot_audit,
            "annotation_sample": sample_audit,
            "pilot_baseline": pilot_summary,
            "annotation_sample_baseline": sample_summary,
            "review_rows": len(review),
            "review_candidate_rows": int((manifest["review_group"] == "candidate").sum()),
            "review_control_rows": int((manifest["review_group"] == "control").sum()),
        },
        config.output_dir / "data_audit.json",
    )
    config.report_path.parent.mkdir(parents=True, exist_ok=True)
    config.report_path.write_text(
        _render_report(pilot_audit, sample_audit, pilot_summary, sample_summary, review, config),
        encoding="utf-8",
    )
    return {
        "pilot_audit": pilot_audit,
        "sample_audit": sample_audit,
        "pilot_summary": pilot_summary,
        "sample_summary": sample_summary,
        "review_rows": len(review),
        "review_path": str(config.output_dir / "human_review_sample.csv"),
        "report_path": str(config.report_path),
    }


def _parse_args() -> argparse.Namespace:
    defaults = ExperimentConfig()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pilot-comments", type=Path, default=defaults.pilot_comments)
    parser.add_argument("--pilot-videos", type=Path, default=defaults.pilot_videos)
    parser.add_argument("--preprocessed-comments", type=Path, default=defaults.preprocessed_comments)
    parser.add_argument("--annotation-sample", type=Path, default=defaults.annotation_sample)
    parser.add_argument("--output-dir", type=Path, default=defaults.output_dir)
    parser.add_argument("--report", type=Path, default=defaults.report_path)
    parser.add_argument("--seed", type=int, default=defaults.seed)
    parser.add_argument("--review-size", type=int, default=defaults.review_size)
    parser.add_argument("--candidate-per-channel", type=int, default=defaults.candidate_per_channel)
    parser.add_argument("--control-per-channel", type=int, default=defaults.control_per_channel)
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    config = ExperimentConfig(
        pilot_comments=args.pilot_comments,
        pilot_videos=args.pilot_videos,
        preprocessed_comments=args.preprocessed_comments,
        annotation_sample=args.annotation_sample,
        output_dir=args.output_dir,
        report_path=args.report,
        review_size=args.review_size,
        candidate_per_channel=args.candidate_per_channel,
        control_per_channel=args.control_per_channel,
        seed=args.seed,
    )
    result = run(config)
    print(f"Pilot rows: {result['pilot_audit']['rows']}; candidates: {result['pilot_summary']['candidate_count']}")
    print(f"Annotation sample rows: {result['sample_audit']['rows']}; candidates: {result['sample_summary']['candidate_count']}")
    print(f"Blinded review rows: {result['review_rows']}")
    print(f"Aggregate report: {result['report_path']}")
    print(f"Review output: {result['review_path']}")


if __name__ == "__main__":
    main()
